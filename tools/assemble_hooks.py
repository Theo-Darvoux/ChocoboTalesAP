"""
Assembles the flag-write hooks injected into Chocobo Tales and writes chocobo_tales/hooks.py.
Needs keystone (installed in ../NDSTools/.venv): ../NDSTools/.venv/bin/python tools/assemble_hooks.py

The game writes every save flag through two wrappers in the ARM9 binary:
  0x02001BE8 set(flag)                  -> tail-calls 0x020041E0(bank, flag)
  0x02001C4C set_field(flag, width, v)  -> calls      0x020042DC(bank, flag, width, v)
(bank = *(0x0209DDE0) + 0x24). The patch redirects both wrappers to these hooks, which skip setting any flag
marked in BLOCKED_BITMAP (flags Archipelago hands out as items) and otherwise do exactly what the wrappers did.
Clearing a flag (set_field with value 0) is never blocked.

The hooks live in ITCM after the game's own ITCM code (an extra 0x260 bytes appended to the ITCM autoload block).
"""
from pathlib import Path

from keystone import KS_ARCH_ARM, KS_MODE_ARM, Ks

BASE = 0x01FFED00  # end of the game's ITCM autoload block (0x01FF8000 + 0x6D00)
BITMAP_OFFSET = 0x100  # the bitmap of blocked flags follows the code
FLAG_COUNT = 0xA80  # flags 0-0xA7F, 0x150 bytes of bitmap
SAVE_POINTER_LITERAL = 0x0209DDDC  # the wrappers load [this + 4]
LOW_LEVEL_SET = 0x020041E0
LOW_LEVEL_SET_FIELD = 0x020042DC

SOURCE = f"""
hook_set:
    cmp   r0, #{FLAG_COUNT:#x}
    bhs   set_go
    ldr   r12, =bitmap
    ldrb  r12, [r12, r0, lsr #3]
    and   r1, r0, #7
    lsr   r12, r12, r1
    tst   r12, #1
    bxne  lr
set_go:
    mov   r1, r0
    ldr   r12, ={SAVE_POINTER_LITERAL:#x}
    ldr   r0, [r12, #4]
    add   r0, r0, #0x24
    ldr   pc, ={LOW_LEVEL_SET:#x}

hook_set_field:
    cmp   r1, #1
    bne   field_go
    cmp   r2, #0
    beq   field_go
    cmp   r0, #{FLAG_COUNT:#x}
    bhs   field_go
    ldr   r12, =bitmap
    ldrb  r12, [r12, r0, lsr #3]
    and   r3, r0, #7
    lsr   r12, r12, r3
    tst   r12, #1
    bxne  lr
field_go:
    mov   r3, r2
    mov   r2, r1
    mov   r1, r0
    ldr   r12, ={SAVE_POINTER_LITERAL:#x}
    ldr   r0, [r12, #4]
    add   r0, r0, #0x24
    ldr   pc, ={LOW_LEVEL_SET_FIELD:#x}
.ltorg
"""


def assemble() -> tuple[bytes, dict[str, int]]:
    ks = Ks(KS_ARCH_ARM, KS_MODE_ARM)
    # keystone can't place a label at a fixed address, so "bitmap" is substituted by its absolute address
    encoding, _ = ks.asm(SOURCE.replace("=bitmap", f"={BASE + BITMAP_OFFSET:#x}"), BASE)
    code = bytes(encoding)
    assert len(code) <= BITMAP_OFFSET, f"hook code too large: {len(code):#x}"
    # hook_set_field starts with the first "cmp r1, #1" (0xE3510001); hook_set has none
    field_offset = code.index(bytes.fromhex("010051e3"))
    assert field_offset % 4 == 0
    return code, {"hook_set": BASE, "hook_set_field": BASE + field_offset}


def main() -> None:
    code, symbols = assemble()
    out = Path(__file__).resolve().parent.parent / "chocobo_tales" / "hooks.py"
    lines = [
        '"""Generated by tools/assemble_hooks.py (see its docstring for what the code does). Do not edit by hand."""',
        "",
        f"BASE = {BASE:#010x}",
        f"BITMAP_OFFSET = {BITMAP_OFFSET:#x}",
        f"FLAG_COUNT = {FLAG_COUNT:#x}",
        f"HOOK_SET = {symbols['hook_set']:#010x}",
        f"HOOK_SET_FIELD = {symbols['hook_set_field']:#010x}",
        f"CODE = bytes.fromhex({code.hex()!r})",
        "",
    ]
    out.write_text("\n".join(lines))
    print(f"{len(code):#x} bytes of code, hook_set {symbols['hook_set']:#x}, hook_set_field {symbols['hook_set_field']:#x} -> {out}")


if __name__ == "__main__":
    main()
